function pct(x) {
  if (x == null) return "—";
  const v = x <= 1 ? x * 100 : x;
  return `${v.toFixed(1)}%`;
}

function formatCoords(loc) {
  if (!loc || loc.lat == null || loc.lon == null) return null;
  const parts = [`${loc.lat}, ${loc.lon}`];
  if (loc.accuracy != null) parts.push(`±${loc.accuracy}m`);
  return parts.join(" ");
}

/** Plain-text report — the fallback when the OS can't take an image share. */
function buildReport(item, t, where) {
  const lines = [
    "PotatoDoc — Diagnosis Report",
    "",
    `${t("Result")}: ${item.class} (${pct(item.confidence)})`,
    `${t("Model")}: ${item.model || "—"}`,
    `${t("Taken on")}: ${item.timestamp || "—"}`,
  ];
  if (where) lines.push(`${t("Location")}: ${where}`);
  const probs = item.probabilities || {};
  const keys = Object.keys(probs);
  if (keys.length) {
    lines.push("", t("Per-Class Probabilities") + ":");
    keys.forEach((k) => lines.push(`  ${k}: ${pct(probs[k])}`));
  }
  lines.push("", "— Generated by PotatoDoc");
  return lines.join("\n");
}

/**
 * Local file if it is still on this device, otherwise the server copy the
 * sync uploaded. Shared by the sheet's preview and the offscreen share card
 * so the same bytes are fetched once and cached by RN's image cache.
 */
function usePhotoUri(item, token) {
  const [uri, setUri] = useState(item?.imageUri || null);
  const [missing, setMissing] = useState(false);

  useEffect(() => {
    let alive = true;
    setUri(item?.imageUri || null);
    setMissing(false);
    if (item?.imageUri) return () => { alive = false; };

    // No local file (merged from another device): pull the server copy.
    if (item?.has_photo && token && item.id != null) {
      (async () => {
        try {
          const res = await axios.get(
            `${API_BASE}/history/${encodeURIComponent(item.id)}/photo`,
            {
              headers: { Authorization: `Bearer ${token}` },
              responseType: "arraybuffer",
              timeout: 20000,
            }
          );
          const bytes = new Uint8Array(res.data);
          let bin = "";
          const CHUNK = 0x8000;
          for (let i = 0; i < bytes.length; i += CHUNK) {
            bin += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
          }
          if (alive) setUri(`data:image/jpeg;base64,${btoa(bin)}`);
        } catch (e) {
          if (alive) setMissing(true);
        }
      })();
    } else {
      setMissing(true);
    }
    return () => { alive = false; };
  }, [item, token]);

  return { uri, missing };
}

