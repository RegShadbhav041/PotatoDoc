function Photo({ uri, missing, s, C, t }) {
  if (uri) {
    return (
      <View style={s.photoWrap}>
        <Image source={{ uri }} style={s.photo} resizeMode="cover" />
      </View>
    );
  }
  if (missing) {
    return (
      <View style={s.photoWrap}>
        <View style={s.photoMissing}>
          <MaterialIcons name="image-not-supported" size={26} color={C.gray} />
          <Text style={s.photoMissingText}>{t("Photo not on this device")}</Text>
        </View>
      </View>
    );
  }
  return null; // fetching — the sheet still renders the rest immediately
}

export default function HistoryDetailModal({ item, visible, onClose, token }) {
  const C = useColors();
  const t = useT();
  const s = useMemo(() => makeStyles(C), [C]);
  const cardRef = useRef(null);
  const { uri: photoUri, missing } = usePhotoUri(item, token);
  const [sharing, setSharing] = useState(false);

  const where =
    item && item.location
      ? [item.location.label, formatCoords(item.location)].filter(Boolean).join(" · ")
      : "";

  const onShare = async () => {
    if (!item || sharing) return;
    setSharing(true);
    try {
      // 1. Preferred: a branded PNG of the report.
      try {
        // Give the offscreen card's <Image> a beat to decode before capture.
        await new Promise((r) => setTimeout(r, 350));
        const uri = await captureRef(cardRef, {
          format: "png",
          quality: 1,
          result: "tmpfile",
        });
        if (uri && (await Sharing.isAvailableAsync())) {
          await Sharing.shareAsync(uri, {
            mimeType: "image/png",
            dialogTitle: t("Share report"),
            UTI: "public.png",
          });
          return;
        }
      } catch (e) {
        console.warn("image share failed", e?.message);
      }
      // 2. Fallback: the plain-text report — always works.
      await Share.share({ message: buildReport(item, t, where) });
    } catch (e) {
      console.warn("share failed", e?.message);
    } finally {
      setSharing(false);
    }
  };

  if (!item) return null;

  return (
    <Modal visible={visible} transparent animationType="slide" onRequestClose={onClose}>
      <Pressable style={s.backdrop} onPress={onClose}>
        <Pressable style={s.sheet} onPress={(e) => e.stopPropagation()}>
          <View style={s.grab} />
          <View style={s.head}>
            <Text style={s.headTitle}>{t("Diagnosis report")}</Text>
            <Pressable style={s.closeBtn} onPress={onClose} hitSlop={8}>
              <MaterialIcons name="close" size={18} color={C.ink} />
            </Pressable>
          </View>

          <ScrollView style={s.scroll} contentContainerStyle={s.scrollContent}>
            <Photo uri={photoUri} missing={missing} s={s} C={C} t={t} />

            <View style={s.metaCard}>
              <View style={s.metaRow}>
                <MaterialIcons name="event" size={15} color={C.primary} />
                <Text style={s.metaText}>{item.timestamp || "—"}</Text>
                <Text style={s.metaMuted}>
                  {relativeTime(item.created_at || item.updated_at)}
                </Text>
              </View>
              <View style={s.metaRow}>
                <MaterialIcons name="location-on" size={15} color={C.primary} />
                <Text style={[s.metaText, !where && { color: C.gray }]}>
                  {where || t("No location tag")}
                </Text>
              </View>
              <View style={s.metaRow}>
                <MaterialIcons name="psychology" size={15} color={C.primary} />
                <Text style={s.metaText}>{item.model || "—"}</Text>
              </View>
            </View>

            {/* The exact output the Diagnose flow rendered for this result. */}
            <PredictionResult
              data={item}
              modelLabel={item.model}
              heatmap={null}
              ensembleHeatmaps={null}
            />
          </ScrollView>

          {/* Pinned footer: reachable no matter how long the report is. */}
          <View style={s.footer}>
            <Pressable
              style={[s.shareBtn, sharing && { opacity: 0.6 }]}
              onPress={onShare}
              disabled={sharing}
            >
              <MaterialIcons name="share" size={18} color="#FFFFFF" />
              <Text style={s.shareText}>
                {sharing ? t("Sharing…") : t("Share report")}
              </Text>
            </Pressable>
          </View>
        </Pressable>
      </Pressable>

      {/* Offscreen capture target for the share image. */}
      {visible ? (
        <View style={s.offscreen} pointerEvents="none">
          <View ref={cardRef} collapsable={false}>
            <ShareReportCard item={item} where={where} photoUri={photoUri} />
          </View>
        </View>
      ) : null}
    </Modal>
  );
}
